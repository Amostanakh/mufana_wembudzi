// animal_model.dart
class Animal {
  final String tagNumber;
  final DateTime birthDate;
  final double weight;
  final String gender;
  final bool isFemale;
  final String father;
  final String mother;
  final String owner;

  Animal({
    required this.tagNumber,
    required this.birthDate,
    required this.weight,
    required this.gender,
    required this.isFemale,
    required this.father,
    required this.mother,
    required this.owner,
  });
}
